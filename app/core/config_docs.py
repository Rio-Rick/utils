"""Render the shipped default YAML files and the configuration reference from the schema.

The schema (:class:`~app.core.config_schema.Setting`) is the single source of truth:
``scripts/gen_config.py`` writes ``config/defaults/*.yaml`` and ``docs/configuration.md``
with these functions and a unit test fails when the committed files are out of date.
"""

from __future__ import annotations

import textwrap
from collections.abc import Mapping, Sequence
from typing import Any

import yaml

from app.core.config_schema import Setting

_INLINE_LIMIT = 72


def _flow(value: Any) -> str:
    return yaml.safe_dump(value, default_flow_style=True, allow_unicode=True, width=10**6, sort_keys=False).strip().removesuffix("...").strip()


def _scalar_line(key: str, value: Any, indent: str) -> list[str]:
    """``key: value`` lines; long lists and mappings use block style."""
    if isinstance(value, (list, dict)) and value:
        inline = _flow(value)
        if len(inline) + len(key) + len(indent) + 2 > _INLINE_LIMIT:
            block = yaml.safe_dump({key: value}, default_flow_style=False, allow_unicode=True, sort_keys=False, width=10**6)
            return [indent + line for line in block.rstrip("\n").split("\n")]
        return [f"{indent}{key}: {inline}"]
    return [f"{indent}{key}: {_flow(value)}"]


def _comment(setting: Setting, indent: str) -> list[str]:
    parts = [setting.label + ("." if not setting.label.endswith(".") else "")]
    if setting.help:
        parts.append(setting.help)
    flags = []
    if setting.advanced:
        flags.append("advanced")
    if setting.restart:
        flags.append("restart required")
    constraint = setting.constraints()
    text = " ".join(parts)
    lines = textwrap.wrap(text, width=96 - len(indent), initial_indent="# ", subsequent_indent="# ")
    suffix = f"({constraint}{'; ' + ', '.join(flags) if flags else ''})"
    lines += textwrap.wrap(suffix, width=96 - len(indent), initial_indent="# ", subsequent_indent="#   ")
    return [indent + line for line in lines]


def _tree(settings: Sequence[Setting]) -> dict[str, Any]:
    """Nested ``{part: subtree | Setting}`` preserving registration order."""
    root: dict[str, Any] = {}
    for setting in settings:
        if setting.inherit:
            continue
        node = root
        *parents, leaf = setting.key.split(".")
        for part in parents:
            child = node.get(part)
            if not isinstance(child, dict):
                child = {}
                node[part] = child
            node = child
        node[leaf] = setting
    return root


def _emit(node: Mapping[str, Any], indent: str, out: list[str], depth: int) -> None:
    for key, child in node.items():
        if isinstance(child, Setting):
            if out and out[-1] != "":
                out.append("")
            out.extend(_comment(child, indent))
            out.extend(_scalar_line(key, child.default, indent))
        else:
            if out and out[-1] != "" and depth == 0:
                out.append("")
            out.append(f"{indent}{key}:")
            _emit(child, indent + "  ", out, depth + 1)


def render_defaults_yaml(domain: str, title: str, settings: Sequence[Setting]) -> str:
    """Commented ``config/defaults/<domain>.yaml`` text."""
    header = [
        f"# {title} - shipped defaults for the '{domain}' domain.",
        "# Generated by scripts/gen_config.py from the settings schema - do not edit.",
        f"# Put your own changes in config/user/{domain}.yaml (or use the Settings page);",
        "# only the values you change are stored there, so updates never overwrite your choices.",
        "",
    ]
    body: list[str] = []
    tree = _tree(settings)
    if not tree:
        return "\n".join(header) + "{}\n"
    _emit(tree, "", body, 0)
    return "\n".join(header + body).rstrip("\n") + "\n"


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _default_md(setting: Setting) -> str:
    if setting.inherit:
        return f"inherits `{setting.inherit}`"
    value = setting.default
    text = _flow(value) if isinstance(value, (list, dict)) else (repr(value) if isinstance(value, str) else str(value).lower() if isinstance(value, bool) else str(value))
    if text == "''":
        text = "(empty)"
    return f"`{_md(text)}`"


def render_reference_markdown(domains: Mapping[str, Sequence[Setting]], titles: Mapping[str, str], descriptions: Mapping[str, str] | None = None) -> str:
    """Markdown reference of every setting (``docs/configuration.md``)."""
    descriptions = descriptions or {}
    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by scripts/gen_config.py from the settings schema. Do not edit by hand. -->",
        "",
        "Every setting can be changed in **Settings** inside the application. Behind the scenes the",
        "values live in YAML files, one per domain:",
        "",
        "| Layer | Location | Purpose |",
        "|---|---|---|",
        "| Shipped defaults | `config/defaults/<domain>.yaml` | Read-only, replaced on update |",
        "| Your overrides | `config/user/<domain>.yaml` (source checkout) or `~/.config/linux-media-toolkit/<domain>.yaml` | Only the values you changed; never replaced on update |",
        "",
        "Resolution order: **your override > shipped default > inherited value > built-in default**.",
        "A value that fails validation is reported in *Settings → Problems* and ignored; the file is",
        "never rewritten or deleted because of it. Set `LMT_CONFIG_DIR` to use another folder.",
        "",
        "Legend: **adv** = shown under *Advanced*; **restart** = applied after restarting;",
        "**sensitive** = machine specific, skipped when importing a configuration unless you confirm.",
        "",
        "Domains: " + ", ".join(f"[`{d}`](#{d})" for d in domains) + ".",
        "",
    ]
    for domain, settings in domains.items():
        lines += [f'<a id="{domain}"></a>', f"## {titles.get(domain, domain)} (`{domain}.yaml`)", ""]
        if descriptions.get(domain):
            lines += [descriptions[domain], ""]
        lines += ["| Key | Values | Default | Description |", "|---|---|---|---|"]
        for setting in settings:
            flags = []
            if setting.advanced:
                flags.append("adv")
            if setting.restart:
                flags.append("restart")
            if setting.sensitive:
                flags.append("sensitive")
            flag_text = f" _({', '.join(flags)})_" if flags else ""
            description = _md(f"{setting.label}. {setting.help}".strip()) + flag_text
            lines.append(f"| `{setting.key}` | {_md(setting.constraints())} | {_default_md(setting)} | {description} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
